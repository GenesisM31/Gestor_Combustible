-- Unified Auditing. Ejecutar como SYS en FREEPDB1.
CREATE AUDIT POLICY pol_sesiones ACTIONS LOGON, LOGOFF;
AUDIT POLICY pol_sesiones;
CREATE AUDIT POLICY pol_admin ACTIONS
  CREATE USER, ALTER USER, DROP USER,
  CREATE ROLE, ALTER ROLE, DROP ROLE,
  CREATE PROFILE, ALTER PROFILE, DROP PROFILE,
  GRANT, REVOKE,
  CREATE TABLE, ALTER TABLE, DROP TABLE;
AUDIT POLICY pol_admin;
